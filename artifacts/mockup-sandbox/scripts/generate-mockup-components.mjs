// Generates src/.generated/mockup-components.ts so that `tsc` can typecheck
// App.tsx without running the Vite dev server first. The same file is
// (re)generated at dev/build time by mockupPreviewPlugin.ts; this script
// mirrors that plugin's discovery logic for static-analysis-only contexts.
import { mkdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import glob from "fast-glob";

const pkgDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const MOCKUPS_DIR = "src/components/mockups";
const GENERATED_MODULE = "src/.generated/mockup-components.ts";

async function main() {
  const files = await glob(`${MOCKUPS_DIR}/**/*.tsx`, {
    cwd: pkgDir,
    ignore: ["**/_*/**", "**/_*.tsx"],
  });

  const entries = files
    .map((f) => {
      const globKey = "./" + f.slice("src/".length);
      const importPath = path.posix.relative("src/.generated", f);
      return `  ${JSON.stringify(globKey)}: () => import(${JSON.stringify(importPath)}),`;
    })
    .join("\n");

  const source = [
    "// This file is auto-generated by scripts/generate-mockup-components.mjs.",
    "// (Also regenerated at dev/build time by mockupPreviewPlugin.ts.)",
    "type ModuleMap = Record<string, () => Promise<Record<string, unknown>>>;",
    "export const modules: ModuleMap = {",
    entries,
    "};",
    "",
  ].join("\n");

  const absPath = path.join(pkgDir, GENERATED_MODULE);
  mkdirSync(path.dirname(absPath), { recursive: true });
  writeFileSync(absPath, source);
  console.log(`wrote ${GENERATED_MODULE} (${files.length} mockup(s))`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
